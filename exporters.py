"""Render an answer or draft to Markdown, PDF or DOCX.

Rendering server side rather than in the browser means the PDF and DOCX get
real typography, keep the heading structure, and carry the list of sources the
answer relied on. The styling matches the project: oxblood headings, a serif
face for reading matter.
"""
from __future__ import annotations

import datetime as dt
import io
import re
from typing import List, Sequence, Tuple


class UnsupportedFormat(ValueError):
    pass


OXBLOOD = "#6E1423"
INK = "#17181C"
SLATE = "#5A6472"

FOOTER = ("Generated by Sanhita, a local retrieval-augmented research tool. "
          "Drafts and answers are produced from an indexed corpus and require "
          "review by a qualified professional before use.")


# ------------------------------------------------------------- markdown ----
def _markdown(title: str, body: str, sources: Sequence[dict]) -> bytes:
    out = [f"# {title}", "",
           f"*{dt.date.today().strftime('%d %B %Y')} · Sanhita*", "", body.strip()]
    if sources:
        out += ["", "---", "", "## Sources", ""]
        for i, s in enumerate(sources, 1):
            src = s.get("source", "?")
            score = s.get("score")
            out.append(f"{i}. **{src}**" + (f" — similarity {score}" if score else ""))
    out += ["", "---", "", f"*{FOOTER}*", ""]
    return "\n".join(out).encode("utf-8")


# ------------------------------------------------------------------ pdf ----
_INLINE = re.compile(r"\*\*(.+?)\*\*")


def _inline(text: str) -> str:
    """Markdown bold/italic -> ReportLab markup, with XML escaped first."""
    t = (text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))
    t = _INLINE.sub(r"<b>\1</b>", t)
    t = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"<i>\1</i>", t)
    t = re.sub(r"`([^`]+)`", r'<font face="Courier">\1</font>', t)
    return t


def _pdf(title: str, body: str, sources: Sequence[dict]) -> bytes:
    from reportlab.lib import colors
    from reportlab.lib.enums import TA_JUSTIFY
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import mm
    from reportlab.platypus import (ListFlowable, ListItem, Paragraph,
                                    SimpleDocTemplate, Spacer)

    buf = io.BytesIO()
    doc = SimpleDocTemplate(buf, pagesize=A4, title=title, author="Sanhita",
                            leftMargin=22 * mm, rightMargin=22 * mm,
                            topMargin=20 * mm, bottomMargin=20 * mm)
    ss = getSampleStyleSheet()
    ox = colors.HexColor(OXBLOOD)
    st_title = ParagraphStyle("t", parent=ss["Title"], fontName="Times-Bold",
                              fontSize=20, leading=24,
                              textColor=colors.HexColor(INK), spaceAfter=3)
    st_meta = ParagraphStyle("m", parent=ss["Normal"], fontName="Times-Italic",
                             fontSize=9.5, textColor=colors.HexColor(SLATE),
                             spaceAfter=13)
    st_h2 = ParagraphStyle("h2", parent=ss["Heading2"], fontName="Helvetica-Bold",
                           fontSize=11.5, leading=15, textColor=ox,
                           spaceBefore=11, spaceAfter=4)
    st_h3 = ParagraphStyle("h3", parent=st_h2, fontSize=10.2,
                           textColor=colors.HexColor(INK))
    st_b = ParagraphStyle("b", parent=ss["BodyText"], fontName="Times-Roman",
                          fontSize=10.6, leading=15.4, alignment=TA_JUSTIFY,
                          spaceAfter=6.5)
    st_s = ParagraphStyle("s", parent=st_b, fontSize=9,
                          textColor=colors.HexColor(SLATE))

    story = [Paragraph(_inline(title), st_title),
             Paragraph(f"{dt.date.today().strftime('%d %B %Y')} &middot; Sanhita", st_meta)]

    bullets: List[str] = []

    def flush():
        if bullets:
            story.append(ListFlowable(
                [ListItem(Paragraph(_inline(b), st_b), leftIndent=11) for b in bullets],
                bulletType="bullet", start="square", bulletColor=ox,
                bulletFontSize=5, leftIndent=12))
            bullets.clear()

    for raw in body.splitlines():
        line = raw.rstrip()
        if not line.strip():
            flush(); story.append(Spacer(1, 3)); continue
        if line.startswith("### "):
            flush(); story.append(Paragraph(_inline(line[4:]), st_h3))
        elif line.startswith("## "):
            flush(); story.append(Paragraph(_inline(line[3:]), st_h2))
        elif line.startswith("# "):
            flush(); story.append(Paragraph(_inline(line[2:]), st_h2))
        elif re.match(r"^\s*[-*]\s+", line):
            bullets.append(re.sub(r"^\s*[-*]\s+", "", line))
        elif line.strip() in ("---", "***"):
            flush(); story.append(Spacer(1, 6))
        else:
            flush(); story.append(Paragraph(_inline(line), st_b))
    flush()

    if sources:
        story += [Spacer(1, 9), Paragraph("Sources", st_h2)]
        for i, s in enumerate(sources, 1):
            sc = s.get("score")
            story.append(Paragraph(
                f"{i}. {_inline(str(s.get('source','?')))}"
                + (f" &mdash; similarity {sc}" if sc else ""), st_s))

    story += [Spacer(1, 11), Paragraph(FOOTER, st_s)]
    doc.build(story)
    return buf.getvalue()


# ----------------------------------------------------------------- docx ----
def _docx(title: str, body: str, sources: Sequence[dict]) -> bytes:
    from docx import Document
    from docx.shared import Pt, RGBColor

    d = Document()
    d.core_properties.title = title
    d.core_properties.author = "Sanhita"
    d.add_heading(title, level=0)
    meta = d.add_paragraph(f"{dt.date.today().strftime('%d %B %Y')} · Sanhita")
    meta.runs[0].italic = True

    def rich(par, text: str):
        """Render **bold** spans as real runs rather than literal asterisks."""
        for i, part in enumerate(re.split(r"\*\*(.+?)\*\*", text)):
            if not part:
                continue
            run = par.add_run(part)
            run.bold = bool(i % 2)

    for raw in body.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        if line.startswith("### "):
            d.add_heading(line[4:], level=3)
        elif line.startswith("## "):
            d.add_heading(line[3:], level=2)
        elif line.startswith("# "):
            d.add_heading(line[2:], level=1)
        elif re.match(r"^\s*[-*]\s+", line):
            rich(d.add_paragraph(style="List Bullet"),
                 re.sub(r"^\s*[-*]\s+", "", line))
        elif line.strip() in ("---", "***"):
            continue
        else:
            rich(d.add_paragraph(), line)

    if sources:
        d.add_heading("Sources", level=2)
        for i, s in enumerate(sources, 1):
            sc = s.get("score")
            d.add_paragraph(f"{i}. {s.get('source','?')}"
                            + (f" — similarity {sc}" if sc else ""),
                            style="List Number" if False else None)

    note = d.add_paragraph(FOOTER)
    note.runs[0].italic = True
    note.runs[0].font.size = Pt(8.5)
    note.runs[0].font.color.rgb = RGBColor(0x5A, 0x64, 0x72)

    buf = io.BytesIO()
    d.save(buf)
    return buf.getvalue()


# ----------------------------------------------------------------- entry ---
def render(fmt: str, title: str, body: str,
           sources: Sequence[dict]) -> Tuple[io.BytesIO, str, str]:
    if fmt in ("md", "markdown"):
        data, mime, ext = _markdown(title, body, sources), "text/markdown", "md"
    elif fmt == "pdf":
        data, mime, ext = _pdf(title, body, sources), "application/pdf", "pdf"
    elif fmt == "docx":
        data, mime, ext = (_docx(title, body, sources),
                           "application/vnd.openxmlformats-officedocument."
                           "wordprocessingml.document", "docx")
    else:
        raise UnsupportedFormat(f"Unsupported format: {fmt}")
    return io.BytesIO(data), mime, ext
